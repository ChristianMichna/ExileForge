import { z } from "zod";
import { AscendancyId, CharacterClassId, GemId, PassiveNodeId } from "../common/ids.js";
import {
  CalcId,
  CalcProfileId,
  DataReleaseId,
  GameVersion,
  PobVersion,
} from "../common/version.js";
import { CalcResult, StatMap } from "./result.js";

/*
 * Calc RPC between calc-client (Node supervisor) and the LuaJIT PoB worker:
 * JSON-RPC 2.0, one JSON object per line over stdin/stdout. The worker
 * reports CALC_PROTOCOL_VERSION via meta.version on start; the supervisor
 * refuses a mismatch.
 */

export const CALC_PROTOCOL_VERSION = 1;

/** Max size of a build payload (PoB XML or code) accepted over RPC, in characters. */
export const MAX_BUILD_PAYLOAD_CHARS = 2_000_000;

/** Worker-local handle of a loaded build state. States are immutable: a patch yields a new handle. */
export const BuildHandle = z.string().min(1).max(128).brand<"BuildHandle">();
export type BuildHandle = z.infer<typeof BuildHandle>;

export const BuildFormat = z.enum(["xml", "code"]);
export type BuildFormat = z.infer<typeof BuildFormat>;

/** Metric names are PoB output names; the target metric sets come from config. */
export const MetricList = z.array(z.string().min(1)).min(1);

/** Weapon set index as used by the game (0 = shared); range is validated by PoB. */
const WeaponSet = z.int().nonnegative();

export const PatchOp = z.discriminatedUnion("op", [
  z.object({ op: z.literal("setLevel"), level: z.int().positive() }),
  z.object({ op: z.literal("setClass"), classId: CharacterClassId }),
  z.object({ op: z.literal("setAscendancy"), ascendancyId: AscendancyId }),
  z.object({
    op: z.literal("allocateNodes"),
    nodeIds: z.array(PassiveNodeId).min(1),
    weaponSet: WeaponSet.optional(),
  }),
  z.object({ op: z.literal("deallocateNodes"), nodeIds: z.array(PassiveNodeId).min(1) }),
  z.object({
    op: z.literal("setSkill"),
    /** Stable key of the skill group inside the build. */
    groupKey: z.string().min(1),
    gemId: GemId,
    level: z.int().positive(),
    quality: z.int().nonnegative(),
    supports: z.array(
      z.object({ gemId: GemId, level: z.int().positive(), quality: z.int().nonnegative() }),
    ),
    weaponSet: WeaponSet.optional(),
  }),
  z.object({ op: z.literal("removeSkill"), groupKey: z.string().min(1) }),
  z.object({
    op: z.literal("setItem"),
    /** PoB slot name. */
    slot: z.string().min(1),
    /** Item in PoB item-text format, generated by ExileForge from an ItemSpec. */
    itemText: z.string().min(1).max(20_000),
  }),
  z.object({ op: z.literal("removeItem"), slot: z.string().min(1) }),
  z.object({
    op: z.literal("setConfig"),
    key: z.string().min(1),
    value: z.union([z.boolean(), z.number(), z.string()]),
  }),
]);
export type PatchOp = z.infer<typeof PatchOp>;

const Deltas = StatMap.describe("Metric -> change against the base state");

const method = <P extends z.ZodType, R extends z.ZodType>(params: P, result: R) => ({
  params,
  result,
});

/** All calc RPC methods with their params and result schemas. */
export const CalcMethods = {
  "meta.version": method(
    z.object({}),
    z.object({
      protocolVersion: z.int().positive(),
      pobVersion: PobVersion,
      /** Game version PoB declares as supported. */
      gameVersion: GameVersion,
      dataReleaseId: DataReleaseId,
    }),
  ),
  "build.load": method(
    z.object({ format: BuildFormat, payload: z.string().min(1).max(MAX_BUILD_PAYLOAD_CHARS) }),
    z.object({ handle: BuildHandle, warnings: z.array(z.string()) }),
  ),
  "build.export": method(
    z.object({ handle: BuildHandle, format: BuildFormat }),
    z.object({ payload: z.string().min(1) }),
  ),
  "build.applyPatch": method(
    z.object({ handle: BuildHandle, ops: z.array(PatchOp).min(1) }),
    z.object({ handle: BuildHandle, warnings: z.array(z.string()) }),
  ),
  "build.release": method(z.object({ handle: BuildHandle }), z.object({})),
  "calc.stats": method(
    z.object({
      handle: BuildHandle,
      profile: CalcProfileId,
      mainSkill: z.string().min(1).optional(),
    }),
    CalcResult,
  ),
  "calc.evalBatch": method(
    z.object({
      handle: BuildHandle,
      profile: CalcProfileId,
      metrics: MetricList,
      candidates: z
        .array(z.object({ key: z.string().min(1), ops: z.array(PatchOp).min(1) }))
        .min(1),
    }),
    z.object({
      base: CalcResult,
      results: z.array(
        z.discriminatedUnion("ok", [
          z.object({ key: z.string(), ok: z.literal(true), calcId: CalcId, deltas: Deltas }),
          z.object({ key: z.string(), ok: z.literal(false), error: z.string().min(1) }),
        ]),
      ),
    }),
  ),
  "calc.nodePower": method(
    z.object({
      handle: BuildHandle,
      profile: CalcProfileId,
      metrics: MetricList,
      /** Absent = all nodes reachable from the current tree. */
      candidates: z.array(PassiveNodeId).min(1).optional(),
    }),
    z.object({
      base: CalcResult,
      results: z.array(
        z.object({
          nodeId: PassiveNodeId,
          calcId: CalcId,
          deltas: Deltas,
          /** Unallocated nodes on the shortest path, including the node itself. */
          pathCost: z.int().positive(),
        }),
      ),
    }),
  ),
  "calc.itemPower": method(
    z.object({
      handle: BuildHandle,
      profile: CalcProfileId,
      metrics: MetricList,
      slot: z.string().min(1),
      /** Mod lines in PoB item-text form to value one by one. */
      modLines: z.array(z.string().min(1)).min(1),
    }),
    z.object({
      base: CalcResult,
      results: z.array(
        z.object({
          modLine: z.string(),
          calcId: CalcId,
          deltas: Deltas,
          parsed: z.boolean(),
        }),
      ),
    }),
  ),
  "calc.validate": method(
    z.object({ handle: BuildHandle }),
    z.object({
      ok: z.boolean(),
      findings: z.array(
        z.object({
          /** Finding code, e.g. requirement, spirit, points, connectivity. */
          code: z.string().min(1),
          message: z.string().min(1),
          subject: z.string().optional(),
        }),
      ),
      unsupportedMods: z.array(z.string()),
    }),
  ),
} as const;

export type CalcMethodName = keyof typeof CalcMethods;
export const CalcMethodName = z.enum(
  Object.keys(CalcMethods) as [CalcMethodName, ...CalcMethodName[]],
);
export type CalcParams<M extends CalcMethodName> = z.infer<(typeof CalcMethods)[M]["params"]>;
export type CalcResultOf<M extends CalcMethodName> = z.infer<(typeof CalcMethods)[M]["result"]>;

export const RpcId = z.union([z.int().nonnegative(), z.string().min(1).max(64)]);

export const CalcRequest = z.object({
  jsonrpc: z.literal("2.0"),
  id: RpcId,
  method: CalcMethodName,
  params: z.unknown(),
});
export type CalcRequest = z.infer<typeof CalcRequest>;

/** Error kinds the worker and supervisor report; JSON-RPC codes stay generic. */
export const CalcErrorKind = z.enum([
  "invalid_params",
  "unknown_method",
  "unknown_handle",
  "build_load_failed",
  "calc_failed",
  "timeout",
  "worker_crashed",
  "protocol_mismatch",
]);
export type CalcErrorKind = z.infer<typeof CalcErrorKind>;

export const CalcError = z.object({
  code: z.int(),
  message: z.string().min(1),
  data: z.object({ kind: CalcErrorKind, detail: z.string().optional() }),
});
export type CalcError = z.infer<typeof CalcError>;

export const CalcResponse = z.union([
  z.object({ jsonrpc: z.literal("2.0"), id: RpcId, result: z.unknown() }),
  z.object({ jsonrpc: z.literal("2.0"), id: RpcId.nullable(), error: CalcError }),
]);
export type CalcResponse = z.infer<typeof CalcResponse>;

/** Validates params for a method; throws with cause on invalid input. */
export function parseCalcParams<M extends CalcMethodName>(
  method: M,
  params: unknown,
): CalcParams<M> {
  const parsed = CalcMethods[method].params.safeParse(params);
  if (!parsed.success) {
    throw new Error(`Invalid params for ${method}`, { cause: parsed.error });
  }
  return parsed.data as CalcParams<M>;
}

/** Validates a method result from the worker; throws with cause on invalid output. */
export function parseCalcResult<M extends CalcMethodName>(
  method: M,
  result: unknown,
): CalcResultOf<M> {
  const parsed = CalcMethods[method].result.safeParse(result);
  if (!parsed.success) {
    throw new Error(`Invalid result for ${method}`, { cause: parsed.error });
  }
  return parsed.data as CalcResultOf<M>;
}
